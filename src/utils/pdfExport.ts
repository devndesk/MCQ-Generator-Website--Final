import jsPDF from 'jspdf';
import { MCQ } from '../types';

export async function downloadAsPDF(mcqs: MCQ[]) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 20;
  const contentWidth = pageWidth - 2 * margin;
  let yPosition = margin;

  // Title
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text('Generated MCQs', pageWidth / 2, yPosition, { align: 'center' });
  yPosition += 15;

  // Date
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`Generated on: ${new Date().toLocaleDateString()}`, pageWidth / 2, yPosition, { align: 'center' });
  yPosition += 15;

  // Draw a line
  doc.setLineWidth(0.5);
  doc.line(margin, yPosition, pageWidth - margin, yPosition);
  yPosition += 10;

  // Process each MCQ
  mcqs.forEach((mcq, index) => {
    // Check if we need a new page
    if (yPosition > pageHeight - 60) {
      doc.addPage();
      yPosition = margin;
    }

    // Question number and text
    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    const questionText = `Q${index + 1}. ${mcq.question}`;
    const questionLines = doc.splitTextToSize(questionText, contentWidth);
    
    questionLines.forEach((line: string) => {
      if (yPosition > pageHeight - 20) {
        doc.addPage();
        yPosition = margin;
      }
      doc.text(line, margin, yPosition);
      yPosition += 7;
    });

    yPosition += 3;

    // Options
    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    mcq.options.forEach((option, optIndex) => {
      if (yPosition > pageHeight - 20) {
        doc.addPage();
        yPosition = margin;
      }

      const optionLabel = String.fromCharCode(65 + optIndex);
      const optionText = `${optionLabel}. ${option}`;
      const optionLines = doc.splitTextToSize(optionText, contentWidth - 10);
      
      optionLines.forEach((line: string) => {
        if (yPosition > pageHeight - 20) {
          doc.addPage();
          yPosition = margin;
        }
        doc.text(line, margin + 5, yPosition);
        yPosition += 6;
      });
    });

    yPosition += 5;

    // Correct Answer
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(0, 128, 0);
    const answerText = `Correct Answer: ${mcq.correctAnswer}`;
    const answerLines = doc.splitTextToSize(answerText, contentWidth);
    
    answerLines.forEach((line: string) => {
      if (yPosition > pageHeight - 20) {
        doc.addPage();
        yPosition = margin;
      }
      doc.text(line, margin + 5, yPosition);
      yPosition += 6;
    });

    // Reset color
    doc.setTextColor(0, 0, 0);

    // Explanation if exists
    if (mcq.explanation) {
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(10);
      const explanationText = `Explanation: ${mcq.explanation}`;
      const explanationLines = doc.splitTextToSize(explanationText, contentWidth);
      
      explanationLines.forEach((line: string) => {
        if (yPosition > pageHeight - 20) {
          doc.addPage();
          yPosition = margin;
        }
        doc.text(line, margin + 5, yPosition);
        yPosition += 5;
      });
    }

    yPosition += 8;

    // Separator line between questions
    if (index < mcqs.length - 1) {
      if (yPosition > pageHeight - 20) {
        doc.addPage();
        yPosition = margin;
      }
      doc.setLineWidth(0.3);
      doc.setDrawColor(200, 200, 200);
      doc.line(margin, yPosition, pageWidth - margin, yPosition);
      yPosition += 8;
    }
  });

  // Footer on each page
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(128, 128, 128);
    doc.text(
      `Page ${i} of ${totalPages}`,
      pageWidth / 2,
      pageHeight - 10,
      { align: 'center' }
    );
    doc.text(
      'Generated by MCQ Master',
      pageWidth - margin,
      pageHeight - 10,
      { align: 'right' }
    );
  }

  // Save the PDF
  doc.save(`MCQs-${Date.now()}.pdf`);
}
